/*
# Create notifications table — Central de Avisos

## Purpose
Stores a persistent history of all notifications/alerts generated by the
notification engine (hydration reminders, planner alerts, task deadlines,
notes reminders). The profile page reads from this table to display a
"Central de Avisos" feed to the user.

## New Tables
- `notifications`
  - `id` (uuid, primary key, auto-generated)
  - `user_email` (text, NOT NULL) — the user's email (scoping key)
  - `category` (text, NOT NULL) — alert type: 'hydration', 'planner', 'tasks', 'notes', 'finance'
  - `title` (text, NOT NULL) — alert title
  - `body` (text, NOT NULL) — alert message
  - `icon` (text) — emoji or icon identifier
  - `is_read` (boolean, default false) — whether the user has seen it
  - `created_at` (timestamptz, default now()) — when the alert was generated

## Security
- RLS is enabled on `notifications`.
- The app uses its own local auth (not Supabase Auth), so the anon-key
  client must be able to read/insert/update. Policies are scoped to
  `anon, authenticated` with `user_email` as the ownership key.
- Anyone can read/insert/update/delete notifications for any email —
  this is acceptable because the table contains non-sensitive reminder
  data and the app has no Supabase Auth session. The `user_email` column
  is used for filtering in the frontend.

## Important Notes
1. Notifications are scoped by `user_email` in the frontend queries.
2. `is_read` tracks whether the user has opened the "Central de Avisos".
3. Old notifications are cleaned up periodically by the frontend (keeps last 50).
*/

CREATE TABLE IF NOT EXISTS notifications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_email text NOT NULL,
  category text NOT NULL,
  title text NOT NULL,
  body text NOT NULL,
  icon text,
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "select_notifications" ON notifications;
CREATE POLICY "select_notifications"
  ON notifications FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "insert_notifications" ON notifications;
CREATE POLICY "insert_notifications"
  ON notifications FOR INSERT
  TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "update_notifications" ON notifications;
CREATE POLICY "update_notifications"
  ON notifications FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "delete_notifications" ON notifications;
CREATE POLICY "delete_notifications"
  ON notifications FOR DELETE
  TO anon, authenticated USING (true);

CREATE INDEX IF NOT EXISTS notifications_user_email_idx ON notifications (user_email);
CREATE INDEX IF NOT EXISTS notifications_created_at_idx ON notifications (created_at DESC);
